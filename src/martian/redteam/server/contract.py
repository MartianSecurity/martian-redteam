"""The ``/v1/redteam`` API as a versioned contract.

``contract/redteam-api-v<N>.json``, N being :data:`REDTEAM_API_VERSION`, is the OpenAPI document of
every red team route and the schemas they use: the core's routes (:mod:`martian.redteam.server`),
generated from the router, and the hosted backend's four SDK operation routes, copied unchanged from
its ``contracts/redteam-operations.json`` into ``contract/redteam-operations.json``.
``scripts/redteam_contract.py`` writes the file, and refuses when the routes changed and
:data:`REDTEAM_API_VERSION` was not raised. ``tests/redteam`` fails when the routes drift from the file.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from fastapi import FastAPI

REDTEAM_API_VERSION = 7
FOLDER = Path(__file__).resolve().parent / "contract"
CONTRACT_PATH = FOLDER / f"redteam-api-v{REDTEAM_API_VERSION}.json"
OPERATIONS_PATH = FOLDER / "redteam-operations.json"


def _refs(value: Any) -> set[str]:
    if isinstance(value, dict):
        found = {value["$ref"].rsplit("/", 1)[-1]} if isinstance(value.get("$ref"), str) else set()
        for item in value.values():
            found |= _refs(item)
        return found
    if isinstance(value, list):
        return set().union(*(_refs(item) for item in value)) if value else set()
    return set()


def core_openapi() -> dict[str, Any]:
    """The OpenAPI document of an application that serves only the core's red team routes."""
    from martian.evals.server.dependencies import current_principal
    from martian.redteam.server import router

    app = FastAPI(title="Martian red team")
    app.dependency_overrides[current_principal] = lambda: None
    app.include_router(router)
    return app.openapi()


def operations() -> dict[str, Any]:
    loaded: dict[str, Any] = json.loads(OPERATIONS_PATH.read_text(encoding="utf-8"))
    return loaded


def build_contract(openapi: dict[str, Any], hosted: dict[str, Any]) -> dict[str, Any]:
    """The red team contract: the core's routes from ``openapi`` and the hosted operation routes
    from ``hosted``, with the schemas each reaches. A schema both define must be the same."""
    from martian.redteam.server import PREFIX

    paths = {path: item for path, item in openapi["paths"].items() if path.startswith(PREFIX)}
    clash = set(paths) & set(hosted["paths"])
    if clash:
        raise ValueError(f"the core and the hosted operations both define {sorted(clash)}")
    core_schemas = openapi.get("components", {}).get("schemas", {})
    wanted: set[str] = set()
    pending = _refs(paths)
    while pending:
        name = pending.pop()
        if name in wanted or name not in core_schemas:
            continue
        wanted.add(name)
        pending |= _refs(core_schemas[name])
    schemas = {name: core_schemas[name] for name in wanted}
    for name, schema in hosted["components"]["schemas"].items():
        if name in schemas and schemas[name] != schema:
            raise ValueError(f"the core and the hosted operations define schema {name} differently")
        schemas[name] = schema
    return {
        "openapi": openapi["openapi"],
        "info": {
            "title": "Martian red team API",
            "version": str(REDTEAM_API_VERSION),
            "description": "Every /v1/redteam route: the red team core's, and the hosted backend's SDK "
            f"operation routes (operations contract version {hosted['info']['version']}). Generated by "
            "scripts/redteam_contract.py; do not edit by hand.",
        },
        "paths": {**paths, **hosted["paths"]},
        "components": {"schemas": {name: schemas[name] for name in sorted(schemas)}},
    }


def render(contract: dict[str, Any]) -> str:
    return json.dumps(contract, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def undeclared_change(old: dict[str, Any] | None, new: dict[str, Any]) -> bool:
    """True when the routes changed but the version did not: the file must not be rewritten."""
    if old is None:
        return False
    same_version = old.get("info", {}).get("version") == new["info"]["version"]
    changed = {k: v for k, v in old.items() if k != "info"} != {k: v for k, v in new.items() if k != "info"}
    return same_version and changed


def generated() -> dict[str, Any]:
    return build_contract(core_openapi(), operations())


def checked_in() -> dict[str, Any]:
    loaded: dict[str, Any] = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    return loaded


